// Scans lib/physics/carData/ (recursively, any subdirectory structure) for
// *.json car presets and writes lib/physics/carData.generated.ts: a plain,
// static import list that the client-side app can actually consume.
//
// Why this exists instead of a runtime directory scan: this Next.js build
// has no glob-import mechanism, is a static export (output: "export", no
// server at runtime), and every consumer of car data is a "use client"
// component - so a runtime fs.readdir is never possible here. This script
// runs at build/dev time instead (see the "predev"/"prebuild" npm scripts)
// and produces the one thing client code *can* consume: ordinary static
// imports, the same shape lib/physics/circuits.ts already hand-writes for
// circuitData/*.json, just generated instead of hand-maintained.
//
// The generated file is gitignored - run `npm run generate:cars` after
// cloning, or just run `npm run dev`/`npm run build`, which do it for you.

import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = fileURLToPath(new URL(".", import.meta.url));
const PHYSICS_DIR = join(SCRIPT_DIR, "..", "lib", "physics");
const CAR_DATA_DIR = join(PHYSICS_DIR, "carData");
const OUTPUT_FILE = join(PHYSICS_DIR, "carData.generated.ts");

const VALID_CATEGORIES = new Set(["minivan", "suv", "supercar", "f1"]);

function walk(dir) {
  let files = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      files = files.concat(walk(full));
    } else if (entry.endsWith(".json")) {
      files.push(full);
    }
  }
  return files;
}

const files = walk(CAR_DATA_DIR).sort();

if (files.length === 0) {
  throw new Error(`No car JSON files found under ${CAR_DATA_DIR}`);
}

const seenIds = new Map(); // id -> file path, for duplicate-id error messages
const imports = [];
const identifiers = [];

files.forEach((file, i) => {
  let data;
  try {
    data = JSON.parse(readFileSync(file, "utf8"));
  } catch (err) {
    throw new Error(`Failed to parse ${file}: ${err.message}`);
  }

  if (!data.id) {
    throw new Error(`Car file missing "id": ${file}`);
  }
  if (seenIds.has(data.id)) {
    throw new Error(`Duplicate car id "${data.id}" in ${file} (already used by ${seenIds.get(data.id)})`);
  }
  seenIds.set(data.id, file);

  if (!VALID_CATEGORIES.has(data.category)) {
    throw new Error(
      `Car file ${file} has unknown category "${data.category}" - expected one of ${[...VALID_CATEGORIES].join(", ")}`,
    );
  }

  const identifier = `car${i}`;
  const importPath = "./" + relative(PHYSICS_DIR, file).split(sep).join("/");
  imports.push(`import ${identifier} from "${importPath}";`);
  identifiers.push(identifier);
});

const output = `// AUTO-GENERATED by scripts/generate-car-data.mjs - do not edit by hand.
// Regenerated automatically before every \`npm run dev\`/\`npm run build\`;
// run \`npm run generate:cars\` directly to refresh it on its own.
import { RealCarPreset } from "./types";

${imports.join("\n")}

// Each import is cast because TS widens JSON string fields (e.g.
// "category": "f1") to plain \`string\`, which doesn't structurally satisfy
// RealCarPreset's union-typed fields without an assertion - the same
// "trust the file, no runtime validation" boundary circuitData/*.json
// already has via CircuitData in circuits.ts.
export const CAR_PRESET_DATA: RealCarPreset[] = [
${identifiers.map((id) => `  ${id} as RealCarPreset,`).join("\n")}
];
`;

writeFileSync(OUTPUT_FILE, output);
console.log(`Generated ${relative(join(SCRIPT_DIR, ".."), OUTPUT_FILE)} from ${files.length} car file(s).`);
